"""Regenerates HCMInternal/ModMenuDefaultLibrary.h from HCMInternal/ModMenuLibrary.xml.

MSVC rejects single string literals longer than ~16KB, so the XML is split into chunks.
Run:  python tools/embed_modmenu_library.py
"""
import os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "HCMInternal", "ModMenuLibrary.xml")
dst = os.path.join(root, "HCMInternal", "ModMenuDefaultLibrary.h")

text = open(src, encoding="utf-8").read().replace("\r\n", "\n")
if ")MML\"" in text:
    sys.exit("ModMenuLibrary.xml must not contain the sequence )MML\"")

CHUNK = 8000
chunks, line_buf = [], ""
for line in text.splitlines(keepends=True):
    if len(line_buf) + len(line) > CHUNK and line_buf:
        chunks.append(line_buf)
        line_buf = ""
    line_buf += line
if line_buf:
    chunks.append(line_buf)

out = ["// GENERATED by tools/embed_modmenu_library.py from ModMenuLibrary.xml. Do not edit by hand.",
       "#pragma once", "#include <cstddef>", "",
       "inline constexpr const char* kModMenuDefaultLibraryChunks[] = {"]
for c in chunks:
    out.append('R"MML(' + c + ')MML",')
out.append("};")
out.append(f"inline constexpr std::size_t kModMenuDefaultLibraryChunkCount = {len(chunks)};")
out.append("")
open(dst, "w", encoding="utf-8", newline="\r\n").write("\n".join(out))
print(f"wrote {dst}: {len(chunks)} chunks, {len(text)} chars")
