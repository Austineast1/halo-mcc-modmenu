"""Regenerates HCMInternal/ModMenuFontsData.h from the TTFs in HCMInternal/fonts.

The fonts (Cinzel and Manrope, SIL Open Font License 1.1) are already subset to Latin-1
so the DLL only grows by ~90KB. Run:  python tools/embed_modmenu_fonts.py
"""
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fonts_dir = os.path.join(root, "HCMInternal", "fonts")
dst = os.path.join(root, "HCMInternal", "ModMenuFontsData.h")

fonts = [
    ("kModMenuFontCinzelSemiBold", "Cinzel-SemiBold.ttf"),
    ("kModMenuFontManropeRegular", "Manrope-Regular.ttf"),
    ("kModMenuFontManropeSemiBold", "Manrope-SemiBold.ttf"),
]

out = ["// GENERATED by tools/embed_modmenu_fonts.py from HCMInternal/fonts. Do not edit by hand.",
       "// Cinzel (c) The Cinzel Project Authors, Manrope (c) The Manrope Project Authors. SIL Open Font License 1.1, see HCMInternal/fonts.",
       "#pragma once", ""]
for name, file in fonts:
    data = open(os.path.join(fonts_dir, file), "rb").read()
    out.append(f"// {file}, {len(data)} bytes")
    out.append(f"alignas(4) inline const unsigned char {name}[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        out.append("\t" + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append("")
open(dst, "w", encoding="utf-8", newline="\r\n").write("\n".join(out))
print(f"wrote {dst}")
